// Generates the test-only, stage-instrumented copy of reference/predicates.c.
//
//   instrument_stages <pristine predicates.c> <output.c>
//
// Every return statement of the four adaptive predicates (and their *adapt
// helpers) is rewritten from
//     return det;
// to
//     { SHEWCHUK_STAGE_HIT(<stage>); return det; }
// so that a test can ask which stage decided a call. Nothing else changes, and
// the test suite checks that the instrumented build returns bit-identical
// values. Each site is keyed on its line number and exact text, so the tool
// fails loudly if it is ever pointed at a different file.
//
// Stage numbers (keep in sync with tests/stages.h):
//   0 A0  orient2d only: decided by the signs of the two products, no bound
//   1 A   first floating-point filter (errboundA)
//   2 B   second filter, after the exact product expansion (errboundB)
//   3 Bx  all coordinate-difference tails are zero, so stage B was exact
//   4 C   third filter with first-order tail corrections (errboundC)
//   5 D   fully exact expansion arithmetic
#include <cstdio>
#include <fstream>
#include <iostream>
#include <iterator>
#include <string>
#include <vector>

namespace {

struct Site {
  int line;  // 1-based line number in the pristine file
  const char* text;  // the line with leading whitespace removed
  int stage;
};

const Site SITES[] = {
    // orient2d
    {1633, "return det;", 0},
    {1639, "return det;", 0},
    {1644, "return det;", 0},
    {1649, "return det;", 1},
    {1578, "return det;", 2},
    {1588, "return det;", 3},
    {1595, "return det;", 4},
    {1616, "return(D[Dlength - 1]);", 5},
    // orient3d
    {2330, "return det;", 1},
    {1978, "return det;", 2},
    {1994, "return det;", 3},
    {2008, "return det;", 4},
    {2288, "return finnow[finlength - 1];", 5},
    // incircle
    {3265, "return det;", 1},
    {2762, "return det;", 2},
    {2773, "return det;", 3},
    {2787, "return det;", 4},
    {3222, "return finnow[finlength - 1];", 5},
    // insphere
    {4258, "return det;", 1},
    {4095, "return det;", 2},
    {4114, "return det;", 3},
    {4151, "return det;", 4},
    {4154, "return insphereexact(pa, pb, pc, pd, pe);", 5},
};

}  // namespace

int main(int argc, char** argv) {
  if (argc != 3) {
    std::cerr << "usage: instrument_stages <predicates.c> <output.c>\n";
    return 2;
  }
  std::ifstream in(argv[1], std::ios::binary);
  if (!in) {
    std::cerr << "cannot read " << argv[1] << "\n";
    return 1;
  }
  std::vector<std::string> lines;
  for (std::string line; std::getline(in, line);) lines.push_back(line);

  for (const Site& site : SITES) {
    if (site.line > static_cast<int>(lines.size())) {
      std::cerr << "line " << site.line << " is past the end of " << argv[1] << "\n";
      return 1;
    }
    std::string& line = lines[site.line - 1];
    const std::size_t indent = line.find_first_not_of(" \t");
    if (indent == std::string::npos || line.substr(indent) != site.text) {
      std::cerr << argv[1] << ":" << site.line << ": expected '" << site.text << "' but found '"
                << line << "'. Is this the pinned reference file?\n";
      return 1;
    }
    line = line.substr(0, indent) + "{ SHEWCHUK_STAGE_HIT(" + std::to_string(site.stage) + "); " +
           site.text + " }";
  }

  std::ofstream out(argv[2], std::ios::binary);
  out << "/* GENERATED by tools/instrument_stages.cpp from reference/predicates.c. Do not edit. */\n";
  for (const std::string& line : lines) out << line << "\n";
  out.close();
  if (!out) {
    std::cerr << "cannot write " << argv[2] << "\n";
    return 1;
  }
  return 0;
}
